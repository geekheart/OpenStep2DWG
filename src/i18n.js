let language = 'zh-CN';
export function normalizeLanguage(value) { return value === 'en' ? 'en' : 'zh-CN'; }
export function setLanguage(value) { language = normalizeLanguage(value); return language; }
export function getLanguage() { return language; }
export function t(key, values = {}, locale = language) {
 const template = messages[normalizeLanguage(locale)][key] ?? messages['zh-CN'][key] ?? key;
 return template.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? `{${name}}`));
}
export function descriptor(key, values = {}) { return {messageKey:key, values}; }
export function localize(message) {
 const values = {...message.values};
 if(values.viewId) values.view = t(`view.${values.viewId}`);
 if(values.methodKey) values.method = t(values.methodKey);
 if(values.checkKey) values.check = t(values.checkKey);
 return t(message.messageKey, values);
}
export function localizedError(key, values = {}) {
 return Object.assign(new Error(localize(descriptor(key, values))), descriptor(key, values));
}
export function errorText(error) {
 return error?.messageKey ? localize(error) : t('technicalError', {detail:error?.message || String(error)});
}
export function reportMessage(report, key, percent, values = {}) {
 const message = descriptor(key, values);
 report(localize(message), percent, message);
}
export function applyLanguage(root = document) {
 root.documentElement.lang = language;
 root.title = t('page.title');
 root.querySelector('meta[name="description"]').content = t('page.description');
 for(const element of root.querySelectorAll('[data-i18n]')) element.textContent = t(element.dataset.i18n);
 for(const attribute of ['aria-label','title','alt']) {
  for(const element of root.querySelectorAll(`[data-i18n-${attribute}]`)) element.setAttribute(attribute, t(element.getAttribute(`data-i18n-${attribute}`)));
 }
}
